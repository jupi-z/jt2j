import { readFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { approve, openTestCMS, type TestCMS } from './helpers';

let cms: TestCMS;
beforeAll(async () => {
  cms = await openTestCMS('review');
}, 120000);
afterAll(async () => {
  await cms?.payload.destroy();
});

async function upload(color: string, name = 'review-revision.png') {
  const data = await sharp({
    create: { width: 4, height: 4, channels: 3, background: color },
  })
    .png()
    .toBuffer();
  return { data, name, mimetype: 'image/png', size: data.length };
}
async function mediaFixture(published = true) {
  const file = await upload('#ffffff');
  const doc = await cms.payload.create({
    collection: 'media',
    draft: true,
    locale: 'fr',
    file,
    data: {
      alt: 'Image de test',
      credit: 'Test suite',
      source: 'Generated bytes',
      rightsStatus: 'pending',
      claims: [
        { category: 'reference', source: 'Test fixture', status: 'pending' },
      ],
    },
  });
  if (published) {
    await cms.payload.update({
      collection: 'media',
      id: doc.id,
      draft: true,
      locale: 'en',
      data: {
        alt: 'Test image',
        rightsStatus: 'approved',
        rightsEvidence: 'Test fixture owned by suite',
      },
    });
    await approve(cms, 'media', doc.id);
  }
  return { doc, file, disk: path.resolve('.media', doc.filename!) };
}

describe('Task 5 review regressions', () => {
  it('rejects an editor replacement before it can delete published bytes', async () => {
    const { doc, file, disk } = await mediaFixture();
    await expect(
      cms.payload.update({
        collection: 'media',
        id: doc.id,
        overrideAccess: false,
        user: cms.users.editor,
        file: await upload('#000000'),
        data: {},
      }),
    ).rejects.toThrow();
    expect(await readFile(disk)).toEqual(file.data);
    expect(
      (
        await cms.payload.findByID({
          collection: 'media',
          id: doc.id,
          overrideAccess: false,
        })
      ).filename,
    ).toBe(doc.filename);
  });

  it('rejects destructive media deletion, including trusted bypass calls', async () => {
    const { doc, file, disk } = await mediaFixture();
    await expect(
      cms.payload.delete({
        collection: 'media',
        id: doc.id,
        overrideAccess: false,
        user: cms.users.publisher,
      }),
    ).rejects.toThrow(/immutable/i);
    await expect(
      cms.payload.delete({ collection: 'media', id: doc.id }),
    ).rejects.toThrow(/immutable/i);
    expect(await readFile(disk)).toEqual(file.data);
  });

  it('rejects published-byte overwrite even when the replacement is requested as a draft', async () => {
    const { doc, file, disk } = await mediaFixture();
    await expect(
      cms.payload.update({
        collection: 'media',
        id: doc.id,
        draft: true,
        overwriteExistingFiles: true,
        overrideAccess: false,
        user: cms.users.editor,
        file: await upload('#000000', doc.filename!),
        data: {},
      }),
    ).rejects.toThrow(/immutable/i);
    expect(await readFile(disk)).toEqual(file.data);
  });

  it('preserves draft binaries and gives a replacement upload a fresh private identity/key', async () => {
    const { doc, file, disk } = await mediaFixture(false);
    const replacement = await upload('#000000', doc.filename!);
    await expect(
      cms.payload.update({
        collection: 'media',
        id: doc.id,
        draft: true,
        overrideAccess: false,
        user: cms.users.editor,
        file: replacement,
        data: {},
      }),
    ).rejects.toThrow(/immutable/i);
    const next = await cms.payload.create({
      collection: 'media',
      draft: true,
      overrideAccess: false,
      user: cms.users.editor,
      file: replacement,
      data: { alt: 'Replacement draft' },
    });
    expect(next.id).not.toBe(doc.id);
    expect(next.filename).not.toBe(doc.filename);
    expect(await readFile(disk)).toEqual(file.data);
    expect(await readFile(path.resolve('.media', next.filename!))).toEqual(
      replacement.data,
    );
    await expect(
      cms.payload.findByID({
        collection: 'media',
        id: next.id,
        overrideAccess: false,
      }),
    ).rejects.toThrow();
  });

  it('rejects crop/reprocessing and upload destinations before they can mutate stored media', async () => {
    const { doc, file, disk } = await mediaFixture();
    await expect(
      cms.payload.update({
        collection: 'media',
        id: doc.id,
        draft: true,
        data: { focalX: 0, focalY: 0 },
      }),
    ).rejects.toThrow(/immutable/i);
    await expect(
      cms.payload.update({
        collection: 'media',
        id: doc.id,
        draft: true,
        data: { prefix: 'changed-storage-prefix' },
      }),
    ).rejects.toThrow(/immutable/i);
    expect(await readFile(disk)).toEqual(file.data);
  });

  it.each([
    'socialLinks.0.label.en',
    'defaultSEO.title.en',
    'defaultSEO.description.en',
  ])('blocks publication with missing %s', async (missing) => {
    for (const locale of ['fr', 'en'] as const) {
      await cms.payload.updateGlobal({
        slug: 'site-settings',
        locale,
        draft: true,
        data: {
          socialLinks: [],
          defaultSEO: { title: null, description: null },
        },
      });
    }
    const data = missing.startsWith('social')
      ? {
          socialLinks: [
            { label: 'Notre page', url: 'https://example.test/jt2j' },
          ],
        }
      : { defaultSEO: { [missing.split('.')[1]]: 'Texte français seulement' } };
    await cms.payload.updateGlobal({
      slug: 'site-settings',
      locale: 'fr',
      draft: true,
      data,
    });
    await expect(approve(cms, 'site-settings')).rejects.toThrow(missing);
    const draft = await cms.payload.findGlobal({
      slug: 'site-settings',
      draft: true,
    });
    expect(JSON.stringify(draft.translationIssues)).toContain(missing);
    if (missing.startsWith('social')) {
      await cms.payload.updateGlobal({
        slug: 'site-settings',
        locale: 'en',
        draft: true,
        data: {
          socialLinks: draft.socialLinks!.map((row) => ({
            ...row,
            label: 'Our page',
          })),
        },
      });
    } else {
      await cms.payload.updateGlobal({
        slug: 'site-settings',
        locale: 'en',
        draft: true,
        data: { defaultSEO: { [missing.split('.')[1]]: 'English copy' } },
      });
    }
    await approve(cms, 'site-settings');
  });

  it('retains enabled features in private drafts while protecting published settings', async () => {
    const current = await cms.payload.findGlobal({
      slug: 'site-settings',
      draft: true,
    });
    await cms.payload.updateGlobal({
      slug: 'site-settings',
      user: cms.users.publisher,
      overrideAccess: false,
      data: {
        _status: 'published',
        publicationApproved: true,
        features: { contactForm: true },
        claims: [
          ...(current.claims ?? []).map((c) => ({
            ...c,
            status: 'approved' as const,
            approvedBy: 'Test publisher',
            evidence: 'Test evidence',
          })),
          {
            category: 'legal',
            source: 'Test-only policy evidence',
            status: 'approved',
            approvedBy: 'Test publisher',
            evidence: 'Test evidence',
          },
        ],
      },
    });
    const published = await cms.payload.findGlobal({
      slug: 'site-settings',
      overrideAccess: false,
    });
    expect(published.features?.contactForm).toBe(true);
    const draft = await cms.payload.updateGlobal({
      slug: 'site-settings',
      locale: 'fr',
      draft: true,
      user: cms.users.editor,
      overrideAccess: false,
      data: { tagline: 'Nouvelle proposition privée' },
    });
    expect(draft.features?.contactForm).toBe(true);
    expect(draft._status).toBe('draft');
    expect(draft.publicationApproved).toBe(false);
    expect(
      (
        await cms.payload.findGlobal({
          slug: 'site-settings',
          overrideAccess: false,
        })
      ).tagline,
    ).toBe(published.tagline);
    await expect(
      cms.payload.updateGlobal({
        slug: 'site-settings',
        user: cms.users.publisher,
        overrideAccess: false,
        data: { _status: 'published' },
      }),
    ).rejects.toThrow(/approval/i);
  });
});
